namespace ChartOfAccounts;

/// <summary>
/// أوضاع تهيئة دليل الحسابات للتحكم في كيفية التعامل مع الحسابات القائمة وضمان الفعالية التكرارية (Idempotency).
/// </summary>
public enum InitializationMode
{
    /// <summary>
    /// الوضع الصارم (Strict): إذا كان دليل الحسابات مهيأ مسبقاً أو توجد حسابات، تفشل العملية فوراً لحماية التوازن المالي.
    /// </summary>
    Strict = 1,

    /// <summary>
    /// وضع الدمج والمطابقة الآمن (Idempotent Merge): يقوم بإضافة الحسابات المفقودة من القالب فقط وربط الأدوار غير المعينة دون المساس بالحسابات الحالية.
    /// </summary>
    IdempotentMerge = 2,

    /// <summary>
    /// وضع المحاكاة والاختبار الجاف (Dry Run): يحاكي عملية التهيئة والتحقق من صحة القواعد دون حفظ أي تغييرات في قاعدة البيانات.
    /// </summary>
    DryRun = 3
}
