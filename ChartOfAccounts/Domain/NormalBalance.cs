

namespace ChartOfAccounts;

/// <summary>
/// يحدد طبيعة الرصيد المحاسبي الطبيعي للحساب (مدين أو دائن).
/// في القيد المزدوج، يزيد الحساب في جانب طبيعته وينقص في الجانب المقابل.
/// </summary>
public enum NormalBalance
{
    /// <summary>
    /// مدين (Debit) - الطبيعة المحاسبية للأصول والمصروفات، وتزيد بالجانب المدين وتنقص بالدائن.
    /// </summary>
    Debit = 1,

    /// <summary>
    /// دائن (Credit) - الطبيعة المحاسبية للالتزامات وحقوق الملكية والإيرادات، وتزيد بالجانب الدائن وتنقص بالمدين.
    /// </summary>
    Credit = 2
}
