

namespace ChartOfAccounts;

/// <summary>
/// يمثل الأنواع الخمسة الرئيسية للحسابات وفقاً للمعايير المحاسبية الدولية (IFRS / GAAP).
/// يحدد نوع الحساب سلوكه في القوائم المالية وطبيعة رصيده الافتراضية.
/// </summary>
public enum AccountType
{
    /// <summary>
    /// الأصول (Assets) - الموارد الاقتصادية التي تملكها أو تسيطر عليها الشركة.
    /// طبيعة الرصيد: مدين (Debit). تظهر في قائمة المركز المالي.
    /// </summary>
    Asset = 1,

    /// <summary>
    /// الخصوم / الالتزامات (Liabilities) - التزامات المنشأة الحالية الناشئة عن أحداث سابقة.
    /// طبيعة الرصيد: دائن (Credit). تظهر في قائمة المركز المالي.
    /// </summary>
    Liability = 2,

    /// <summary>
    /// حقوق الملكية (Equity) - الحصة المتبقية في أصول المنشأة بعد خصم جميع التزاماتها.
    /// طبيعة الرصيد: دائن (Credit). تظهر في قائمة المركز المالي.
    /// </summary>
    Equity = 3,

    /// <summary>
    /// الإيرادات (Revenue) - التدفقات النقدية أو الزيادات الأخرى في الأصول الناشئة عن أنشطة المنشأة الاعتيادية.
    /// طبيعة الرصيد: دائن (Credit). تظهر في قائمة الدخل.
    /// </summary>
    Revenue = 4,

    /// <summary>
    /// المصروفات (Expenses) - النقص في المنافع الاقتصادية خلال الفترة المحاسبية في شكل تدفقات خارجة.
    /// طبيعة الرصيد: مدين (Debit). تظهر في قائمة الدخل.
    /// </summary>
    Expense = 5
}
